/** Display only our translated messages, never server-supplied error text. */
export function errorMessage(error: ApiError): MessageKey {
  switch (error.kind) {
    case "https":
      return "auth.httpsRequired";
    case "network":
      return "api.network";
    case "format":
      return "api.format";
    case "server":
      return serverMessages.get(error.code ?? "") ?? "api.server";
  }
}
